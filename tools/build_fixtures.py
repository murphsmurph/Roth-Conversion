def ser(o):
    if isinstance(o, D):
        s = str(o)
        return float(s) if "." in s else int(s)
    if isinstance(o, dict):
        return {k: ser(v) for k, v in o.items()}
    if isinstance(o, list):
        return [ser(v) for v in o]
    return o

INDEX = []

def emit(folder, fid, title, tests, inputs, expected, notes=None, tolerance=0.01, authority=None):
    doc = {
        "id": fid,
        "title": title,
        "tax_year": 2026,
        "law_mode": "current_law",
        "tests": tests,
        "authority": authority or [],
        "input": ser(inputs),
        "expected": ser(expected),
        "tolerance_dollars": tolerance,
        "notes": notes or "",
        "oracle": "hand-traced IRS worksheet; see tools/oracle.py — NOT generated by src/engine",
    }
    path = os.path.join(ROOT, folder, fid + ".json")
    with open(path, "w") as f:
        json.dump(doc, f, indent=2)
    INDEX.append({"id": fid, "folder": folder, "title": title, "tests": tests})
    return doc

