def pair(folder, fid, title, base, delta_conversion, tests, authority, notes_a="", notes_b=""):
    """Emit a baseline/conversion pair and record the effective marginal rate between them.
    Pairs are how the engine's MARGINAL behaviour gets tested, not just its level."""
    r_, rb = fed(**base)
    emit(folder, fid + "a", title + " — baseline", tests, base, keyexp(rb),
         authority=authority, notes=notes_a)
    conv = dict(base); conv["roth_conversion"] = base.get("roth_conversion", 0) + delta_conversion
    r_, rc = fed(**conv)
    e = keyexp(rc)
    e["_pair_delta"] = {
        "baseline_fixture": fid + "a",
        "delta_conversion": D(delta_conversion),
        "delta_taxable_social_security": rc["step3_taxable_social_security"] - rb["step3_taxable_social_security"],
        "delta_taxable_income": rc["step7_taxable_income"] - rb["step7_taxable_income"],
        "delta_senior_bonus_deduction": rc["step6_deductions"]["senior_bonus_deduction"] - rb["step6_deductions"]["senior_bonus_deduction"],
        "delta_niit": rc["step9_niit"] - rb["step9_niit"],
        "delta_total_federal_tax": rc["total_federal_tax"] - rb["total_federal_tax"],
        "effective_marginal_rate_on_conversion":
            ((rc["total_federal_tax"] - rb["total_federal_tax"]) / D(delta_conversion)).quantize(D("0.000001")),
    }
    emit(folder, fid + "b", title + f" — +${delta_conversion:,} conversion", tests, conv, e,
         authority=authority, notes=notes_b)

