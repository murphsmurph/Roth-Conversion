#!/usr/bin/env node
// Generates docs/ADVISOR-REVIEW-PACKET.md from the versioned rules JSON, so the values a reviewer
// signs off are EXACTLY the constants the engine runs on (R3 — single source of truth). Run:
//   node tools/build-review-packet.mjs   (or: npm run build:review)
import { readFileSync, writeFileSync } from "node:fs";

const read = p => JSON.parse(readFileSync(p, "utf8"));
const fed = read("src/rules/federal/2026.json");
const med = read("src/rules/medicare/2026.json");
const aca = read("src/rules/aca/2026.json");
const state = read("src/rules/state/2026.json");
const F = fed.rules;

const usd = n => "$" + Number(n).toLocaleString("en-US",
  { minimumFractionDigits: Number.isInteger(Number(n)) ? 0 : 2, maximumFractionDigits: 2 });
const pct = n => (Number(n) * 100).toFixed(2).replace(/\.00$/, "") + "%";
// each data row ends with an empty reviewer sign-off cell
const row = (...cells) => "| " + cells.join(" | ") + " | ☐ |";
const H = (...cells) => "| " + cells.join(" | ") + " | ✓ |\n|" + cells.concat("").map(() => "---").join("|") + "|";

const L = [];
const p = s => L.push(s);

p(`# Advisor review packet — 2026 tax constants`);
p(``);
p(`> **Purpose.** Every tax constant the engine uses is listed below with its value, authority, and`);
p(`> source, generated directly from the versioned rules files (\`src/rules/**\`). A qualified reviewer`);
p(`> (CPA or EA) checks each value against the cited primary source, ticks the ☐ box, initials each`);
p(`> section, and completes the attestation at the end. **This document is generated — do not edit by`);
p(`> hand; run \`npm run build:review\` after any rules change.**`);
p(``);
p(`- **Generated:** from federal \`${fed.ruleSetId}\`, medicare \`${med.ruleSetId}\`, aca \`${aca.ruleSetId}\`, state \`${state.ruleSetId}\`.`);
p(`- **Machine-verification pass:** ${fed.verifiedDate} (cross-checked against independent secondary reproductions of the official releases; primary \`.gov\` pages were egress-blocked, so this is corroboration, **not** a substitute for this review).`);
p(`- **Current \`verifiedBy\`:** \`${fed.verifiedBy}\` on every file — this packet is the step that changes it.`);
p(``);
p(`## How to use`);
p(`1. For each row, open the cited source and confirm the value. Tick ☐ → ☑ (or strike + correct).`);
p(`2. If a value is wrong, **do not edit this file** — note it, fix the rules JSON (with source), and`);
p(`   regenerate. Fixtures and the engine update from the same constants.`);
p(`3. Initial each section header. Complete the attestation block at the end.`);
p(`4. After sign-off, set \`verifiedBy\` in each \`src/rules/**/2026.json\` to the reviewer + date.`);
p(``);
p(`---`);
p(``);

// ---- Federal ----
p(`## 1. Federal — ${fed.primaryAuthority}`);
p(`Primary source: ${fed.sourceUrl}  ·  Secondary: ${fed.secondaryConfirmation}  ·  Section initials: ______`);
p(``);
p(H("Constant", "Value", "Authority / source"));
for (const s of ["single", "mfj", "hoh", "mfs"]) if (F.STD_DEDUCTION.values[s] != null) p(row(`Standard deduction (${s.toUpperCase()})`, usd(F.STD_DEDUCTION.values[s]), F.STD_DEDUCTION.authority));
for (const s of ["single", "mfj"]) p(row(`Age-65 std add-on (${s.toUpperCase()}, per person)`, usd(F.ADDITIONAL_STD_DEDUCTION_AGE_65.values[s]), F.ADDITIONAL_STD_DEDUCTION_AGE_65.authority));
for (const s of ["single", "mfj"]) {
  const b = F.ORDINARY_BRACKETS[s].map(x => `${pct(x[1])}@${usd(x[0])}`).join(", ");
  p(row(`Ordinary brackets (${s.toUpperCase()})`, b, F.ORDINARY_BRACKETS.authority));
}
for (const s of ["single", "mfj"]) {
  const t = F.PREFERENTIAL_RATE_THRESHOLDS[s];
  p(row(`LTCG/QD 0%→15% / 15%→20% (${s.toUpperCase()})`, `${usd(t.zeroRateTop)} / ${usd(t.fifteenRateTop)}`, F.PREFERENTIAL_RATE_THRESHOLDS.authority));
}
const ss = F.SOCIAL_SECURITY_TAXABILITY;
for (const s of ["single", "mfj"]) p(row(`SS taxability base 1 / base 2 (${s.toUpperCase()})`, `${usd(ss.base1[s])} / ${usd(ss.base1[s] + ss.base2Additional[s])}`, `${ss.authority} (${ss.indexedForInflation ? "indexed" : "UNINDEXED"})`));
p(row(`SS inclusion rates`, `${pct(ss.lowerInclusionRate)} / ${pct(ss.maxInclusionRate)}`, ss.authority));
const sd = F.SENIOR_BONUS_DEDUCTION;
p(row(`OBBBA senior deduction / person`, `${usd(sd.amountPerQualifyingIndividual)} (age ${sd.minimumAge}+), TY ${sd.firstTaxYear}–${sd.lastTaxYear}`, sd.authority));
p(row(`Senior phaseout start (S / MFJ) & rate`, `${usd(sd.phaseoutStartMagi.single)} / ${usd(sd.phaseoutStartMagi.mfj)} @ ${pct(sd.phaseoutRatePerQualifyingIndividual)}/person`, `${sd.worksheet}. ${sd.status || ""}`));
p(row(`NIIT rate & thresholds (S / MFJ)`, `${pct(F.NIIT.rate)} · ${usd(F.NIIT.thresholds.single)} / ${usd(F.NIIT.thresholds.mfj)}`, F.NIIT.authority));
p(row(`Charitable AGI floor (itemizers)`, pct(F.CHARITABLE_AGI_FLOOR.floorRateOfAgi), `${F.CHARITABLE_AGI_FLOOR.authority} — ${F.CHARITABLE_AGI_FLOOR.status}`));
p(row(`Non-itemizer charitable (S / MFJ)`, `${usd(F.CHARITABLE_NONITEMIZER_DEDUCTION.values.single)} / ${usd(F.CHARITABLE_NONITEMIZER_DEDUCTION.values.mfj)}`, `${F.CHARITABLE_NONITEMIZER_DEDUCTION.authority}`));
p(row(`Itemized benefit cap`, `${pct(F.ITEMIZED_DEDUCTION_BENEFIT_CAP.maxRate)} on the ${pct(F.ITEMIZED_DEDUCTION_BENEFIT_CAP.appliesToBracket)} bracket`, F.ITEMIZED_DEDUCTION_BENEFIT_CAP.authority));
p(row(`QCD limit (per person / MFJ)`, `${usd(F.QCD_LIMIT.amountPerIndividual)} / ${usd(F.QCD_LIMIT.amountMfj)} (age ${F.QCD_LIMIT.minimumAge}+)`, F.QCD_LIMIT.authority));
const ra = F.RMD_APPLICABLE_AGE.byBirthYear.map(b => `${b.maxBirthYear === null ? "1960+" : "≤" + b.maxBirthYear}→${b.age}`).join(", ");
p(row(`RMD applicable age by birth year`, ra, F.RMD_APPLICABLE_AGE.authority));
const ult = F.RMD_UNIFORM_LIFETIME_TABLE.distributionPeriodByAge;
p(row(`Uniform Lifetime Table (spot: 73 / 75 / 80 / 90)`, `${ult["73"]} / ${ult["75"]} / ${ult["80"]} / ${ult["90"]}`, F.RMD_UNIFORM_LIFETIME_TABLE.authority));
p(row(`RMD ordering (first-dollars-out)`, F.RMD_ORDERING.ruleId, F.RMD_ORDERING.authority));
p(``);

// ---- Medicare / IRMAA ----
p(`## 2. Medicare IRMAA — ${med.primaryAuthority}`);
p(`Source: ${med.sourceUrl}  ·  Std Part B: **${usd(med.standardPartBPremiumMonthly)}/mo**, ${med.magiSourceTaxYear} MAGI (${med.lookbackYears}-yr lookback), per enrollee.  ·  Section initials: ______`);
p(``);
p(H("Filing / tier", "MAGI upper bound", "Part B /mo · Part D IRMAA /mo"));
for (const s of ["single", "mfj"]) for (const t of med.tiers[s]) {
  p(row(`${s.toUpperCase()} · ${t.ruleId}`, t.magiMax === null ? "no upper bound" : `≤ ${usd(t.magiMax)}`, `${usd(t.partBMonthly)} · ${usd(t.partDIrmaaMonthly)}`));
}
p(``);

// ---- ACA ----
p(`## 3. ACA premium-tax-credit cliff — ${aca.primaryAuthority}`);
p(`Source: ${aca.sourceUrl}  ·  Section initials: ______`);
p(``);
p(H("Constant", "Value", "Authority / note"));
const fpl = aca.federalPovertyGuidelines2025;
p(row(`2025 FPL (1 / 2 / 3 / 4 person)`, `${usd(fpl["1"])} / ${usd(fpl["2"])} / ${usd(fpl["3"])} / ${usd(fpl["4"])}`, `HHS 2025 (${fpl.region})`));
p(row(`FPL additional per person`, usd(fpl.additionalPerPerson), fpl.note));
p(row(`Subsidy cliff`, `${aca.subsidyCliff.thresholdPercentOfFpl}% FPL, active=${aca.subsidyCliff.active}`, aca.subsidyCliff.statutoryBasis));
p(row(`Watch item`, aca.subsidyCliff.watchItem.bill, `${aca.subsidyCliff.watchItem.status} — ${aca.subsidyCliff.watchItem.url}`));
p(``);

// ---- State ----
p(`## 4. State income tax (validated-engine v1) — ${state.primaryAuthority}`);
p(`Source: ${state.sourceUrl}  ·  Section initials: ______`);
p(``);
p(H("Item", "Value", "Note"));
p(row(`No-income-tax states (0% ordinary)`, state.noOrdinaryIncomeTaxStates.join(", "), "modeled as data; every other state needs an advisor-supplied effective rate — never guessed"));
p(row(`Coverage model`, "v1 flat-rate", state.coverageModel));
p(``);
p(`> Note: the live projection UI uses a separate, richer 50-state table (legacy engine). The`);
p(`> validated optimizer panel uses this v1 flat-rate model and discloses NOT-MODELED states.`);
p(``);

// ---- Reviewer awareness: known divergences ----
p(`## 5. For the reviewer's awareness — known modeling divergences`);
p(`From \`tests/unit/legacy-crosscheck.test.ts\`. The **validated** engine (optimizer panel) is the`);
p(`more accurate of the two; the **legacy** engine (year-by-year projection table) differs in two ways:`);
p(``);
p(`1. **OBBBA senior deduction** — modeled by the validated engine, **not** by the legacy engine, so`);
p(`   the legacy table over-states tax for clients 65+.`);
p(`2. **Dividends in SS provisional income** — included by the validated engine per IRC 86, **omitted**`);
p(`   by the legacy engine, so the legacy table under-taxes Social Security when SS and dividends`);
p(`   coincide.`);
p(``);
p(`Resolved rule decisions (see \`docs/tax-rules/modeling-decisions.md\`, \`RMD-08-discrepancy.md\`):`);
p(`exact brackets vs. the <$100k Tax Table (≤~$6/yr), full-cents vs. whole-dollar rounding (<$1/line),`);
p(`and RMD-08 corrected at the generator. No open rule decisions remain.`);
p(``);

// ---- Attestation ----
p(`## 6. Attestation`);
p(``);
p(`I have reviewed the tax constants above against their cited authorities for tax year 2026.`);
p(``);
p(`| Field | Entry |`);
p(`|---|---|`);
p(`| Reviewer name | ______________________________ |`);
p(`| Credential (CPA / EA) & license # | ______________________________ |`);
p(`| Firm | ______________________________ |`);
p(`| Exceptions noted (see §s) | ______________________________ |`);
p(`| Signature | ______________________________ |`);
p(`| Date | ______________________________ |`);
p(``);
p(`On sign-off, set \`verifiedBy\` in \`src/rules/federal|medicare|aca|state/2026.json\` to the reviewer`);
p(`name + date, and regenerate this packet.`);
p(``);
p(`_Generated by \`tools/build-review-packet.mjs\`. Not tax advice; a planning-tool provenance record._`);

writeFileSync("docs/ADVISOR-REVIEW-PACKET.md", L.join("\n") + "\n");
console.log("wrote docs/ADVISOR-REVIEW-PACKET.md");
